data class PresetProviderTemplate(
    val id: String,
    val name: String,
    val nameEn: String = name,
    val protocol: ProviderProtocol,
    val defaultBaseUrl: String,
    val description: String,
    val descriptionEn: String = description,
    val categories: Set<PresetCategory> = setOf(PresetCategory.RECOMMENDED),
    val placeholderKey: String = "sk-...",
    val iconName: String = "model",
    val iconChar: String = name.take(1),
    val iconCharEn: String = nameEn.take(1),
    val iconColor: Color = Color(0xFF2563EB),
    val iconBgColor: Color = Color(0x1F2563EB),
    val tagText: String = "厂商",
    val tagType: PresetTagType = PresetTagType.OFFICIAL,
    val isCustomCard: Boolean = false
) {
    fun displayName(isZh: Boolean): String = if (isZh) name else nameEn
    fun displayIconChar(isZh: Boolean): String = if (isZh) iconChar else iconCharEn
    fun displayDescription(isZh: Boolean): String = if (isZh) description else descriptionEn
}

